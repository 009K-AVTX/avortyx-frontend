"""Builds the self-hosted icon font: public/assets/avx-icons/icons.woff2 + icons.css.

The site only uses Font Awesome Pro *solid* icons, so instead of loading the whole kit from
ka-p.fontawesome.com, this keeps just the glyphs the pages and scripts reference, in one small
font next to a CSS file that keeps the usual markup working (<i class="fa-solid fa-check">).

Run it again after using a new icon:
    pip install fonttools brotli
    python3 scripts/build-icons.py
"""
import re
import sys
import urllib.request
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'public/assets/avx-icons'
KIT = 'https://ka-p.fontawesome.com/assets/97f7211792/37312945/kit.css?token=97f7211792'
TOKEN = 'token=97f7211792'
HEADERS = {'Referer': 'https://avortyx-prototype.vercel.app/', 'User-Agent': 'Mozilla/5.0'}
# icons whose names are put together in code ('fa-' + name), so a plain scan can't see them
EXTRA = []


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS)) as r:
        return r.read()


def used_icons():
    names = set(EXTRA)
    files = [*ROOT.glob('src/**/*.jsx'), *ROOT.glob('src/**/*.js'), *ROOT.glob('public/assets/**/*.js')]
    for f in files:
        names.update(re.findall(r'\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)', f.read_text(encoding='utf-8', errors='ignore')))
    return names


def parse_ranges(spec):
    out = []
    for part in spec.split(','):
        lo, _, hi = part.strip()[2:].partition('-')
        out.append((int(lo, 16), int(hi or lo, 16)))
    return out


def main():
    kit = fetch(KIT).decode('utf-8')
    # icon name -> codepoint, from rules like .fa-check-circle,.fa-circle-check{--fa:"\f058"...}
    codes = {}
    for sels, val in re.findall(r'((?:\.fa-[a-z0-9-]+,?)+)\{--fa:"([^"]+)"', kit):
        esc = re.match(r'\\([0-9a-fA-F]+)', val)
        cp = int(esc.group(1), 16) if esc else ord(val[0])
        for name in re.findall(r'\.fa-([a-z0-9-]+)', sels):
            codes[name] = cp
    # the solid 900 font is split over several files, each covering a unicode-range
    faces = []
    for body in re.findall(r'@font-face\{([^}]*)\}', kit):
        if '"Font Awesome 6 Pro"' not in body or 'font-weight:900' not in body:
            continue
        url = re.search(r'url\(([^)]+\.woff2)\)', body).group(1)
        rng = re.search(r'unicode-range:([^;}]+)', body)
        faces.append((url, parse_ranges(rng.group(1)) if rng else None))

    icons = {n: codes[n] for n in sorted(used_icons()) if n in codes}
    # ranges overlap, and the browser tries the last declared face first: do the same, and
    # take each glyph from the first file (in that order) that really has it
    fonts, by_file = {}, {}
    for name, cp in icons.items():
        for url, r in reversed(faces):
            if r and not any(lo <= cp <= hi for lo, hi in r):
                continue
            if url not in fonts:
                fonts[url] = fetch(url + '?' + TOKEN)
            if cp in TTFont(BytesIO(fonts[url])).getBestCmap():
                by_file.setdefault(url, set()).add(cp)
                break
        else:
            sys.exit(f'no glyph for fa-{name}')

    parts = []
    for i, (url, cps) in enumerate(sorted(by_file.items())):
        font = TTFont(BytesIO(fonts[url]))
        opts = subset.Options()
        opts.layout_features = []
        opts.name_IDs = ['*']
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=cps)
        sub.subset(font)
        path = OUT / f'.part{i}.ttf'
        OUT.mkdir(parents=True, exist_ok=True)
        font.flavor = None
        font.save(path)
        parts.append(path)

    merged = Merger().merge([str(p) for p in parts])
    for p in parts:
        p.unlink()
    merged.flavor = 'woff2'
    merged.save(OUT / 'icons.woff2')

    rules = ''.join(f'.fa-{n}{{--fa:"\\{cp:x}"}}\n' for n, cp in icons.items())
    (OUT / 'icons.css').write_text(
        '/* Font Awesome Pro solid icons used on this site, self-hosted. Generated by scripts/build-icons.py */\n'
        '@font-face{font-family:"Font Awesome 6 Pro";font-style:normal;font-weight:900;font-display:block;'
        'src:url(/assets/avx-icons/icons.woff2) format("woff2")}\n'
        '.fa-solid,.fas{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;'
        'display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;'
        'text-rendering:auto;font-family:"Font Awesome 6 Pro";font-weight:900}\n'
        '.fa-solid::before,.fas::before{content:var(--fa)}\n' + rules,
        encoding='utf-8')
    missing = sorted(used_icons() - set(icons) - {'solid'})
    print(f'{len(icons)} icons from {len(parts)} font files -> {OUT.relative_to(ROOT)}')
    if missing:
        print('not icons (ignored):', ' '.join(missing), file=sys.stderr)


main()
